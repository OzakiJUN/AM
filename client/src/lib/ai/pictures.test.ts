import assert from 'node:assert/strict';
import { idlePostBlocked, livePictures, PICTURE_TTL, pictureFile, sourceLink } from './pictures.ts';
const now = Date.now();
const p = { mediaId: '123', activity: 'leisure:1', at: now, source: 'https://example.com/image', text: '看看' };
assert.equal(livePictures([p], now + PICTURE_TTL - 1).length, 1);
assert.equal(livePictures([p], now + PICTURE_TTL).length, 0);
assert.equal(livePictures([p], now - 1).length, 0);
assert.deepEqual(livePictures([...Array(8)].map((_, i) => ({ ...p, mediaId: String(i + 1) })), now).map(p => p.mediaId), ['4','5','6','7','8']);
assert.deepEqual(livePictures([null, {}, { ...p, mediaId: 'garbage' }, { ...p, activity: '' }], now), []);
assert.equal(sourceLink('javascript:alert(1)'), '');
assert.equal(sourceLink('https://user:secret@example.com/p?a=secret#secret'), 'https://example.com/p');
for (const mime of ['image/png', 'image/jpeg', 'image/gif', 'image/webp']) assert.equal(pictureFile({ data: btoa('123'), mime }, 3).size, 3);
assert.throws(() => pictureFile({ data: btoa('1234'), mime: 'image/png' }, 3), /上限/);
assert.throws(() => pictureFile({ data: '', mime: 'image/png' }, 3), /为空/);
assert.throws(() => pictureFile({ data: btoa('123'), mime: 'image/svg+xml' }, 3), /只支持/);
assert.ok(idlePostBlocked(true, 'send_picture', {}, false));
assert.ok(idlePostBlocked(true, 'send_to_channel', {}, true));
assert.ok(idlePostBlocked(true, 'use_helper', { show: true }, true));
assert.ok(!idlePostBlocked(true, 'keep_picture', {}, true));
assert.ok(!idlePostBlocked(false, 'send_picture', {}, true));
console.log('picture limits, expiry, source links and idle guard ok');
